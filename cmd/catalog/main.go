// writeMarkdownModuleFile writes the per-metric details for a single module.
func writeMarkdownModuleFile(w io.Writer, m catalog.Module) {
	fmt.Fprintf(w, "# Module: %s\n\n", m.Name)
	fmt.Fprintf(w, "**%d metrics.**\n\n", len(m.Entries))
	fmt.Fprintln(w, "Back to [overview](README.md).")
	fmt.Fprintln(w)

	if len(m.Entries) == 0 {
		if m.Description != "" {
			fmt.Fprintf(w, "%s\n\n", m.Description)
		} else {
			fmt.Fprintln(w, "*No entries — module has not been catalogued yet.*")
			fmt.Fprintln(w)
		}
		return
	}

	for _, e := range m.Entries {
		writeMarkdownEntry(w, e)
	}
}

// writeMarkdownEntry writes the H3 detail block for a single metric — used
// by both the single-file and per-module writers.
func writeMarkdownEntry(w io.Writer, e catalog.Entry) {
	fmt.Fprintf(w, "### `%s`\n\n", e.Name)
	fmt.Fprintf(w, "%s\n\n", e.Help)
	fmt.Fprintf(w, "**Type:** %s — **Value:** %s\n\n",
		e.MetricType.String(), mdValueType(e))
	if e.Enum != nil {
		fmt.Fprintf(w, "**Enum `%s`:**\n\n", e.Enum.Name)
		fmt.Fprintln(w, "| Code | Label |")
		fmt.Fprintln(w, "|---|---|")
		for _, v := range e.Enum.Values {
			fmt.Fprintf(w, "| %d | %s |\n", v.Code, v.Label)
		}
		fmt.Fprintln(w)
	}
	fmt.Fprintf(w, "**Value source:** `%s` → `%s`\n\n",
		mdEscape(e.Value.Path), mdEscape(e.Value.Field))
	if e.Value.OriginalPath != "" {
		fmt.Fprintf(w, "**Original source:** `%s`\n\n", mdEscape(e.Value.OriginalPath))
	}
	if len(e.Labels) == 0 {
		fmt.Fprintln(w, "**Labels:** none.")
		fmt.Fprintln(w)
		return
	}
	fmt.Fprintln(w, "**Labels:**")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "| Name | Endpoint | Field | Description |")
	fmt.Fprintln(w, "|---|---|---|---|")
	for _, l := range e.Labels {
		endpoint := l.Path
		if endpoint == "" {
			endpoint = "*(same as value)*"
		} else {
			endpoint = "`" + mdEscape(endpoint) + "`"
		}
		field := l.Field
		if field == "" {
			field = "*(constant)*"
		} else {
			field = "`" + mdEscape(field) + "`"
		}
		fmt.Fprintf(w, "| `%s` | %s | %s | %s |\n",
			mdEscape(l.Name), endpoint, field, mdEscape(l.Description))
	}
	fmt.Fprintln(w)
}

// mdValueType returns the value type string for markdown cells. For int_enum
// entries it includes the enum name for quick reference.
func mdValueType(e catalog.Entry) string {
	if e.ValueType == catalog.ValueIntEnum && e.Enum != nil {
		return "int\\_enum (" + e.Enum.Name + ")"
	}
	return e.ValueType.String()
}

// mdEscape escapes pipe characters and backticks that would confuse the
// enclosing table cell or inline-code span. Callers wrap the result in
// backticks or a plain cell as appropriate.
func mdEscape(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	// Backticks inside cells are rendered as literal characters by common
	// markdown parsers, but keep escaping conservative.
	return s
}
